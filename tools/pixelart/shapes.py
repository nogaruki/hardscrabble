def _line(g, a, b, ch):
    (x0, y0), (x1, y1) = a, b
    n = max(abs(x1 - x0), abs(y1 - y0))
    for i in range(n + 1):
        x, y = round(x0 + (x1 - x0) * i / n), round(y0 + (y1 - y0) * i / n)
        g[y][x] = ch


def bow_pulling(stage):
    """BOW with the string drawn back to a nock point and an arrow laid along the axis (stage 0, 1, 2).
    Extra chars: x/y arrowhead, v/w fletching (colours in ARROW_EXTRA)."""
    g = [list(r.replace("D", ".")) for r in pix._rows(BOW)]
    nx, ny = [(6, 9), (5, 10), (4, 11)][stage]
    _line(g, (2, 2), (nx, ny), "D")
    _line(g, (nx, ny), (13, 13), "D")
    for i in range(1, 8):
        g[ny - i][nx + i] = "d"                      # shaft: lit core + shadow below-right
        g[ny - i + 1][nx + i] = "a"
    hx, hy = nx + 8, ny - 8
    g[hy][hx], g[hy + 1][hx], g[hy][hx - 1], g[hy - 1][hx + 1] = "y", "x", "x", "y"  # head
    g[ny][nx - 1], g[ny + 1][nx] = "w", "v"          # fletching
    return ["".join(r) for r in g]


