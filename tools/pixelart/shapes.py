RUST_OF_IRON = [None, 1, 2, 3, 3, 4]  # iron shade -> rusted_iron shade under a blotch (outline 0 stays iron)


def rust(img):
    """Repaint iron-ramp pixels that fall on RUST_MASK with the rusted_iron ramp (in place). Returns img."""
    iron, rusty = ramp("iron"), ramp("rusted_iron")
    px = img.load()
    for y in range(img.height):
        for x in range(img.width):
            c = px[x, y]
            if c in iron and RUST_MASK[y % 16][x % 16] == "r":
                s = RUST_OF_IRON[iron.index(c)]
                if s is not None:
                    px[x, y] = rusty[s]
    return img


def tool(kind, material):
    """16x16 RGBA image of a tool type in a material ramp (wood-only types ignore the material)."""
    if material == "rusted_iron":
        return rust(tool(kind, "iron"))
    if kind in FILLS:
        return pix.render([BUCKET, BUCKET_FILL], digit=material, upper=FILLS[kind])
    grids, accent = TOOLS[kind]
    if material in STONE_MATERIALS and kind in STONE_TOOLS:
        grids = STONE_TOOLS[kind]
    if kind in ("club", "cudgel"):
        material = "wood"
    return pix.render(grids, digit=material, upper=accent or "string", extra=ARROW_EXTRA)


def _check():
    for kind, (grids, _) in TOOLS.items():
        for g in grids:
            rows = pix._rows(g)
            assert len(rows) == 16 and len(rows[0]) == 16, f"{kind}: grid is {len(rows[0])}x{len(rows)}, must be 16x16"
    for kind, grids in STONE_TOOLS.items():
        for g in grids:
            assert len(pix._rows(g)) == 16 and len(pix._rows(g)[0]) == 16, f"stone {kind}: grid must be 16x16"


_check()


def targets():
    """[(path, kind, material)] for every tool/weapon texture under textures/item that a shape covers."""
    kinds = sorted(list(TOOLS) + list(FILLS), key=len, reverse=True)
    out = []
    for p in sorted((pix.TEXTURES / "item").glob("*.png")):
        name = p.stem
        for mat_prefix in sorted(MATERIAL_OF_PREFIX, key=len, reverse=True):
            if name.startswith(mat_prefix + "_"):
                rest = name[len(mat_prefix) + 1:]
                if rest in kinds:
                    out.append((p, rest, MATERIAL_OF_PREFIX[mat_prefix]))
                break
    return out


def main(argv):
    if argv[:1] == ["write"]:
        for p, k, m in targets():
            print(p.relative_to(pix.ROOT), k, m)
            if "--dry" not in argv:
                pix.save(tool(k, m), p)
        return 0
    out = argv[1] if len(argv) > 1 else str(pix.ROOT / "build/art/tools.png")
    shown = [(f"{m}_{k}", tool(k, m)) for k in list(TOOLS) + list(FILLS) for m in ("copper", "iron", "mithril")]
    print(pix.contact_sheet(shown, out, scale=6, cols=9))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:] or ["sheet"]))
